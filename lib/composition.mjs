function webIamAccountService() {
  return `// Generated by sdkwork-scaffold. Regenerate instead of editing by hand.
import { createClient, type SdkworkAppConfig } from '@sdkwork/iam-app-sdk';

export type IamAccountConfig = Pick<
  SdkworkAppConfig,
  'baseUrl' | 'tokenManager' | 'headers' | 'tenantId' | 'organizationId'
>;

export interface IamAccountProfile {
  readonly id?: string;
  readonly displayName?: string;
  readonly email?: string;
  readonly phone?: string;
  readonly tenantId?: string;
  readonly organizationId?: string;
  readonly sessionId?: string;
}

export type IamAccountSnapshot =
  | { readonly status: 'authenticated'; readonly profile: IamAccountProfile }
  | { readonly status: 'unavailable'; readonly reason: string };

function pickString(source: Record<string, unknown>, keys: readonly string[]): string | undefined {
  for (const key of keys) {
    const value = source[key];
    if (typeof value === 'string' && value.trim().length > 0) return value;
  }
  return undefined;
}

function normalizeAccount(
  profile: Record<string, unknown>,
  session: Record<string, unknown>,
): IamAccountProfile {
  return {
    id: pickString(profile, ['id', 'userId', 'user_id']),
    displayName: pickString(profile, ['displayName', 'display_name', 'nickname', 'name']),
    email: pickString(profile, ['email']),
    phone: pickString(profile, ['phone', 'mobile']),
    tenantId: pickString(profile, ['tenantId', 'tenant_id'])
      ?? pickString(session, ['tenantId', 'tenant_id']),
    organizationId: pickString(profile, ['organizationId', 'organization_id'])
      ?? pickString(session, ['organizationId', 'organization_id']),
    sessionId: pickString(session, ['sessionId', 'session_id', 'id']),
  };
}

export function createIamAccountService(config: IamAccountConfig) {
  const client = createClient(config);

  return {
    async load(): Promise<IamAccountSnapshot> {
      try {
        const session = await client.auth.sessions.current.retrieve();
        let profile: Record<string, unknown> = {};
        try {
          profile = await client.iam.users.current.retrieve();
        } catch {
          // A valid session can exist before the profile projection is readable.
        }
        return {
          status: 'authenticated',
          profile: normalizeAccount(profile, session),
        };
      } catch (error) {
        return {
          status: 'unavailable',
          reason: error instanceof Error ? error.message : 'IAM session is unavailable.',
        };
      }
    },

    async signOut(): Promise<void> {
      await client.auth.sessions.current.delete();
    },
  };
}
`;
}

