function patchWebAppPackage(target, options, components, architectureId) {
  const packagePath = path.join(target, applicationRootPath(options.code, resolveArchitecture(architectureId)), 'package.json');
  const manifest = readJsonFile(packagePath);
  manifest.dependencies = manifest.dependencies ?? {};
  const linked = components
    .map((component) => component.architectures[architectureId])
    .filter((integration) => integration?.supported
      && integration.mode === 'linked'
      && integration.language === 'typescript'
      && integration.packageName);
  for (const integration of linked) {
    manifest.dependencies[integration.packageName] = 'workspace:*';
  }
  if (linked.length > 0) {
    manifest.dependencies['@sdkwork/sdk-common'] = 'workspace:*';
    manifest.dependencies['@sdkwork/utils'] = 'workspace:*';
    const entries = Object.entries(manifest.dependencies)
      .sort(([left], [right]) => left.localeCompare(right));
    manifest.dependencies = Object.fromEntries(entries);
  }
  writeJson(target, path.relative(target, packagePath), manifest);
}

function patchFlutterPubspec(target, options, components, architectureId) {
  const appRoot = applicationRootPath(options.code, resolveArchitecture(architectureId));
  const pubspecPath = path.join(target, appRoot, 'pubspec.yaml');
  if (!fs.existsSync(pubspecPath)) return;
  const pathDependencies = components
    .map((component) => ({ component, integration: component.architectures[architectureId] }))
    .filter(({ integration }) => integration?.supported
      && integration.mode === 'linked'
      && ['dart', 'flutter'].includes(integration.language)
      && integration.packageName
      && integration.sdkPath);
  if (pathDependencies.length === 0) return;
  let source = fs.readFileSync(pubspecPath, 'utf8');
  const lines = pathDependencies.map(({ integration }) => {
    const relative = path.relative(path.join(target, appRoot), integration.sdkPath).replaceAll('\\', '/');
    return `  ${integration.packageName}:\n    path: ${relative}`;
  }).join('\n');
  source = source.replace(/^dependencies:\n/mu, `dependencies:\n${lines}\n`);
  fs.writeFileSync(pubspecPath, source, 'utf8');
}

function patchAppComponentSpec(target, options, components, architectureId) {
  const appRoot = applicationRootPath(options.code, resolveArchitecture(architectureId));
  const specPath = path.join(target, appRoot, 'specs', 'component.spec.json');
  if (!fs.existsSync(specPath)) return;
  const spec = readJsonFile(specPath);
  spec.contracts = spec.contracts ?? {};
  const dependencies = components
    .filter((component) => component.kind !== 'runtime')
    .map((component) => ({ component, integration: component.architectures[architectureId] }))
    .filter(({ integration }) => integration?.supported && integration.mode !== 'unavailable')
    .map(({ component, integration }) => ({
      workspace: component.sdkFamily ?? component.id,
      permissionModuleId: component.permissionModuleId,
      surface: integration.apiSurface === 'app'
        ? 'app-api'
        : integration.apiSurface === 'open'
          ? 'open-api'
          : integration.apiSurface === 'backend'
            ? 'backend-api'
            : integration.apiSurface === 'internal'
              ? 'internal-api'
              : (integration.apiSurface ?? 'app-api'),
      credentialMode: integration.credentialMode ?? 'authenticated-app-api',
      packageName: integration.packageName ?? null,
      architecture: architectureId,
    }));
  spec.contracts.sdkDependencies = dependencies;
  spec.contracts.permissionComposition = spec.contracts.permissionComposition ?? {};
  writeJson(target, path.relative(target, specPath), spec);
}

function appendWorkspaceEntries(target, entries) {
  if (entries.length === 0) return;
  const workspacePath = path.join(target, 'pnpm-workspace.yaml');
  if (!fs.existsSync(workspacePath)) return;
  let source = fs.readFileSync(workspacePath, 'utf8');
  const missing = entries.filter((entry) => !source.includes(`"${entry}"`) && !source.includes(`'${entry}'`) && !source.includes(`- ${entry}`));
  if (missing.length === 0) return;
  const block = missing.map((entry) => `  - "${entry}"`).join('\n');
  if (!/^packages:\n(?:  - .*\n)+/mu.test(source)) {
    throw new Error('pnpm-workspace.yaml has no packages list to extend.');
  }
  source = source.replace(/^packages:\n((?:  - .*\n)+)/mu, (_match, list) => `packages:\n${list}${block}\n`);
  fs.writeFileSync(workspacePath, source, 'utf8');
}

function appendReadmeComponents(target, components) {
  const readmePath = path.join(target, 'README.md');
  if (!fs.existsSync(readmePath)) return;
  let source = fs.readFileSync(readmePath, 'utf8');
  if (source.includes('<!-- components:start -->')) return;
  const section = `\n<!-- components:start -->\n## Integrated Components\n\n${componentTable(components)}\n\n<!-- components:end -->\n`;
  source = `${source.trimEnd()}\n${section}`;
  fs.writeFileSync(readmePath, source, 'utf8');
}

function patchManifest(target, components, architectures) {
  const manifestPath = path.join(target, 'agent.app.config.json');
  const manifest = readJsonFile(manifestPath);
  manifest.metadata = manifest.metadata ?? {};
  manifest.metadata.scaffold = manifest.metadata.scaffold ?? {};
  manifest.metadata.scaffold.architectures = architectures;
  manifest.metadata.scaffold.components = components.map((component) => component.id);
  manifest.publish = manifest.publish ?? {};
  const platforms = [...new Set(architectures.flatMap((id) => resolveArchitecture(id).publishPlatforms))];
  manifest.publish.platforms = platforms;
  manifest.publish.installPlatforms = platforms;
  writeJson(target, 'agent.app.config.json', manifest);
}

export function writeComponentIntegration({
  target,
  options,
  components,
  architectures,
  generatedAt,
}) {
  const written = [];
  const roots = architectureRoots(options);
  const iamSelected = components.some((component) => component.id === 'iam');
  const settings = {
    specsRelFromRepo: path.relative(target, path.resolve(options.workspace, 'sdkwork-specs')).replaceAll('\\', '/'),
  };

  const aggregate = {
    schemaVersion: 1,
    kind: 'sdkwork.scaffold.component-selection',
    generatedAt,
    architectures,
    components: componentSummary(components),
  };
  written.push(writeJson(target, 'specs/components.selected.json', aggregate));

  const docs = [];
  for (const component of components) {
    const config = componentConfigDocument(component, architectures[0]);
    written.push(writeJson(target, `config/components/${component.id}.json`, config));
    written.push(writeFile(target, `docs/components/${component.id}.md`, componentDoc(component, settings)));
    docs.push(component);
  }

  written.push(writeFile(
    target,
    'docs/components/README.md',
    `# Component Integration\n\nGenerated component selection for \`sdkwork-${options.code}\`.\n\n${componentTable(docs)}\n\nMachine authority: \`specs/components.selected.json\`. Per-component runtime configuration lives in \`config/components/<id>.json\`.\n`,
  ));

  for (const architectureId of architectures) {
    const architecture = resolveArchitecture(architectureId);
    const appRoot = applicationRootPath(options.code, architecture);
    ensureCommonAppFiles(target, options, architecture, settings.specsRelFromRepo);
    written.push(writeJson(target, `${appRoot}/specs/integration.plan.json`, {
      schemaVersion: 1,
      kind: 'sdkwork.scaffold.architecture-integration',
      architecture: architectureId,
      title: architecture.title,
      kindName: architecture.kind,
      language: architecture.language,
      runtime: architecture.runtime,
      components: components.map((component) => ({
        id: component.id,
        title: component.title,
        supported: Boolean(component.architectures[architectureId]?.supported),
        mode: component.architectures[architectureId]?.mode ?? 'unavailable',
        language: component.architectures[architectureId]?.language ?? null,
        packageName: component.architectures[architectureId]?.packageName ?? null,
        sdkPath: component.architectures[architectureId]?.sdkPathFromTarget ?? null,
        reason: component.architectures[architectureId]?.reason ?? null,
      })),
    }));
    for (const component of components) {
      written.push(writeJson(
        target,
        `${appRoot}/config/components/${component.id}.json`,
        componentConfigDocument(component, architectureId),
      ));
    }

    if (architecture.kind === 'web') {
      written.push(writeFile(
        target,
        `${appRoot}/src/composition/components.ts`,
        tsComponentRegistry(components, architectureId),
      ));
      written.push(writeFile(
        target,
        `${appRoot}/src/composition/sdkClients.ts`,
        tsSdkClients(components, architectureId),
      ));
      const iam = components
        .find((component) => component.id === 'iam')
        ?.architectures[architectureId];
      if (iam?.supported && iam.packageName === '@sdkwork/iam-app-sdk') {
        written.push(writeFile(
          target,
          `${appRoot}/src/account/iam-account.ts`,
          webIamAccountService(),
        ));
      }
      patchWebAppPackage(target, options, components, architectureId);
    } else if (architecture.kind === 'mini-program') {
      written.push(writeFile(
        target,
        `${appRoot}/src/composition/components.ts`,
        tsComponentRegistry(components, architectureId),
      ));
      written.push(writeFile(
        target,
        `${appRoot}/src/composition/architectures.ts`,
        miniArchitectureRegistry(roots),
      ));
    } else if (architecture.kind === 'flutter') {
      written.push(writeFile(
        target,
        `${appRoot}/lib/composition/component_registry.dart`,
        flutterRegistry(components, architectureId),
      ));
      written.push(writeFile(
        target,
        `${appRoot}/lib/composition/architecture_registry.dart`,
        flutterArchitectureRegistry(roots),
      ));
      patchFlutterPubspec(target, options, components, architectureId);
    } else if (architecture.kind === 'ios') {
      const moduleName = iosModuleName(options.code);
      written.push(writeFile(
        target,
        `${appRoot}/App/Bootstrap/ComponentRegistry.swift`,
        iosRegistry(components, architectureId, moduleName),
      ));
      written.push(writeFile(
        target,
        `${appRoot}/App/Bootstrap/ArchitectureRegistry.swift`,
        iosArchitectureRegistry(moduleName, roots),
      ));
    } else if (architecture.kind === 'android') {
      const namespace = androidNamespace(options.code);
      written.push(writeFile(
        target,
        `${appRoot}/app/src/main/kotlin/${namespace.replaceAll('.', '/')}/bootstrap/ComponentRegistry.kt`,
        androidRegistry(components, architectureId, namespace),
      ));
      written.push(writeFile(
        target,
        `${appRoot}/app/src/main/kotlin/${namespace.replaceAll('.', '/')}/bootstrap/ArchitectureRegistry.kt`,
        androidArchitectureRegistry(namespace, roots),
      ));
    } else if (architecture.kind === 'harmony') {
      written.push(writeFile(
        target,
        `${appRoot}/entry/src/main/ets/composition/ComponentRegistry.ets`,
        harmonyRegistry(components, architectureId),
      ));
      written.push(writeFile(
        target,
        `${appRoot}/entry/src/main/ets/composition/ArchitectureRegistry.ets`,
        harmonyArchitectureRegistry(roots),
      ));
    }

    patchAppComponentSpec(target, options, components, architectureId);
  }

  const webArchitectures = architectures.filter((id) => resolveArchitecture(id).kind === 'web');
  if (webArchitectures.length > 0) {
    appendWorkspaceEntries(
      target,
      collectWebSdkWorkspaceEntries({
        workspace: options.workspace,
        target,
        resolvedComponents: components,
        architectures: webArchitectures,
      }),
    );
  }

  written.push(writeJson(target, 'specs/capabilities/catalog.json', {
    schemaVersion: 1,
    kind: 'sdkwork.scaffold.capability-catalog',
    application: `sdkwork-${options.code}`,
    capabilities: [
      {
        id: 'foundation',
        title: 'Application foundation',
        version: '1.0.0',
        category: 'platform',
        states: ['ready'],
      },
      {
        id: 'surfaces',
        title: 'Architecture surfaces',
        version: '1.0.0',
        category: 'platform',
        architectures: roots.map((root) => root.id),
      },
      {
        id: 'components',
        title: 'Component composition',
        version: '1.0.0',
        category: 'platform',
        selected: components.map((component) => component.id),
      },
      {
        id: 'me',
        title: 'My account',
        version: '1.0.0',
        category: 'identity',
        requires: ['iam'],
        selected: iamSelected,
        contract: {
          session: 'auth.sessions.current',
          profile: 'iam.users.current',
          signOut: 'auth.sessions.current.delete',
        },
        projections: {
          web: iamSelected ? 'src/account/iam-account.ts' : null,
          mobile: 'Overview / Surfaces / Components / Me',
        },
      },
    ],
  }));

  patchManifest(target, components, architectures);
  appendReadmeComponents(target, components);
  return written;
}
