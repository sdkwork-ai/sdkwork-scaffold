function ensureDirectory(directory) {
  fs.mkdirSync(directory, { recursive: true });
}

function writeFile(target, relativePath, content) {
  const absolute = path.resolve(target, relativePath);
  ensureDirectory(path.dirname(absolute));
  fs.writeFileSync(absolute, content, 'utf8');
  return relativePath.replaceAll('\\', '/');
}

function writeJson(target, relativePath, value) {
  return writeFile(target, relativePath, `${JSON.stringify(value, null, 2)}\n`);
}

function readJsonFile(file) {
  return JSON.parse(fs.readFileSync(file, 'utf8').replace(/^\uFEFF/u, ''));
}

function quote(value) {
  return JSON.stringify(String(value ?? ''));
}

function componentStatus(component, architectureId) {
  const integration = component.architectures[architectureId] ?? {};
  return {
    id: component.id,
    title: component.title,
    category: component.category,
    description: component.description,
    repo: component.repo,
    kind: component.kind ?? 'sdk',
    sdkFamily: component.sdkFamily ?? null,
    supported: Boolean(integration.supported),
    mode: integration.mode ?? 'unavailable',
    language: integration.language ?? null,
    sdkPackage: integration.packageName ?? null,
    apiSurface: integration.apiSurface ?? null,
    credentialMode: integration.credentialMode ?? null,
    reason: integration.reason ?? null,
    permissions: component.permissions ?? [],
    config: component.selectedConfig ?? {},
  };
}

