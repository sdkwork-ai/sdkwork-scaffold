function componentTable(components) {
  if (components.length === 0) return '_No common component selected._';
  const rows = components.map((component) => {
    const sdk = component.sdkFamily ? `\`${component.sdkFamily}\`` : (component.kind === 'runtime' ? 'runtime package' : '—');
    return `| ${component.title} | \`${component.id}\` | ${component.category} | ${sdk} | ${Object.entries(component.architectures).filter(([, entry]) => entry.supported).map(([id]) => id).join(', ') || '—'} |`;
  });
  return [
    '| Component | Id | Category | SDK family | Supported architectures |',
    '| --- | --- | --- | --- | --- |',
    ...rows,
  ].join('\n');
}

